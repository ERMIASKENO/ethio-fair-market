export const DICTS: Record<Lang, Dict> = { en, am };

export function normalizeLang(v: string | undefined | null): Lang {
  return v === 'am' ? 'am' : 'en';
}

/** Picks the right language from an {en, am} object. */
export function pick(name: { en: string; am: string } | undefined, lang: Lang): string {
  if (!name) return '';
  return name[lang] || name.en;
}
